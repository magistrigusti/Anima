def get_response(user_input: str) -> str:
    clean_text = user_input.strip()

    if not clean_text:
        return "Я рядом. Напиши пару слов о том, что сейчас происходит."

    return (
        "Я слышу тебя. Давай разберем это бережно: "
        "что именно произошло, какое чувство сильнее всего сейчас, "
        "и какой маленький шаг мог бы сделать ближайшие минуты спокойнее?"
    )
